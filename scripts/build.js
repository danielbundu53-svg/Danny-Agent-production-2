/* Builds the files the website needs to run without any outside service:
     public/css/site.css   all styling (Tailwind), minified
     public/js/icons.js    only the icons the pages use
   Run after changing page markup or adding icons:  npm run build          */

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");
process.env.BROWSERSLIST_IGNORE_OLD_DATA = "1";

const root = path.join(__dirname, "..");
const publicDir = path.join(root, "public");

/* ---------- 1. CSS ---------- */
fs.mkdirSync(path.join(publicDir, "css"), { recursive: true });
execFileSync(
  process.execPath,
  [
    path.join(root, "node_modules", "tailwindcss", "lib", "cli.js"),
    "-i", path.join(root, "src", "tailwind.css"),
    "-o", path.join(publicDir, "css", "site.css"),
    "--minify"
  ],
  { stdio: ["ignore", "ignore", "inherit"], cwd: root }
);

/* ---------- 2. Icons ----------
   Collects every quoted word in the pages and scripts, keeps the ones that are
   icon names, and writes just those icons. A few extra bytes for an unused name
   is harmless; a missing icon would show as empty space, so we err on including. */
const lucide = require("lucide");

const kebab = name => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Za-z])([0-9])/g, "$1-$2").toLowerCase();
const known = new Map();
for (const [name, node] of Object.entries(lucide.icons)) known.set(kebab(name), node);

/* Brand icons were removed from Lucide, so they are drawn here (outline style, 24x24). */
const custom = {
  facebook: [["path", { d: "M18 2h-3a5 5 0 0 0-5 5v3H7v4h3v8h4v-8h3l1-4h-4V7a1 1 0 0 1 1-1h3z" }]],
  instagram: [
    ["rect", { x: "2", y: "2", width: "20", height: "20", rx: "5", ry: "5" }],
    ["path", { d: "M16 11.37A4 4 0 1 1 12.63 8 4 4 0 0 1 16 11.37z" }],
    ["line", { x1: "17.5", y1: "6.5", x2: "17.51", y2: "6.5" }]
  ]
};

const files = [];
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) { if (entry.name !== "images" && entry.name !== "css") walk(full); }
    else if (/\.(html|js)$/.test(entry.name) && entry.name !== "icons.js") files.push(full);
  }
})(publicDir);

const wanted = new Set(Object.keys(custom));
for (const file of files) {
  const text = fs.readFileSync(file, "utf8");
  for (const match of text.matchAll(/["'`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)["'`]/g)) {
    if (known.has(match[1])) wanted.add(match[1]);
  }
}

const icons = {};
for (const name of [...wanted].sort()) icons[name] = custom[name] || known.get(name);

const output =
  "/* Generated by scripts/build.js. Do not edit by hand. */\n" +
  "window.SITE_ICONS = " + JSON.stringify(icons) + ";\n";
fs.writeFileSync(path.join(publicDir, "js", "icons.js"), output);

const size = f => (fs.statSync(path.join(publicDir, f)).size / 1024).toFixed(1) + " KB";
console.log(`css/site.css ${size("css/site.css")}, js/icons.js ${size("js/icons.js")} (${Object.keys(icons).length} icons)`);
